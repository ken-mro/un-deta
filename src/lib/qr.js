// QR コードエンコーダ（自前実装・外部依存なし）。バイトモードのみ、型番 1〜40、誤り訂正 L/M/Q/H。
// アルゴリズムは ISO/IEC 18004 に従う。
// modules[y][x] が true のとき暗（黒）モジュール。

const ECL = {
  L: { index: 0, formatBits: 1 },
  M: { index: 1, formatBits: 0 },
  Q: { index: 2, formatBits: 3 },
  H: { index: 3, formatBits: 2 },
};

// [誤り訂正レベル][型番] → 1ブロックあたりの誤り訂正符号語数
